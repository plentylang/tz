//! Writes the expected values of `Zoned.until` and `Zoned.since` for
//! `tests/test_until_jiff.plenty`, computed by jiff:
//!
//!     cargo run --manifest-path scripts/jiff-until/Cargo.toml > tests/test_until_jiff.plenty
//!
//! jiff reads the system's zone files, so check that they agree with the
//! bundled tzdata for these zones before regenerating. Only `Compatible`
//! appears, as jiff always resolves the intermediate reading that way.
//! Cases where jiff panics or where this package deliberately differs are
//! left out; `tests/test_until.plenty` covers them.
use jiff::{Span, Unit, Zoned};

const PAIRS: &[(&str, &str)] = &[
    // Plain differences in one zone.
    ("2024-01-15T08:00:00-05:00[America/New_York]", "2024-06-20T17:45:30.25-04:00[America/New_York]"),
    ("1990-06-15T08:00:00+01:00[Europe/London]", "2024-06-14T07:59:59.5+01:00[Europe/London]"),
    ("2024-05-01T23:00:00+10:00[Australia/Sydney]", "2024-05-02T01:00:00+10:00[Australia/Sydney]"),
    // Month-end clamping and leap years.
    ("2024-01-31T12:00:00+00:00[UTC]", "2024-02-29T12:00:00+00:00[UTC]"),
    ("2024-01-31T12:00:00+00:00[UTC]", "2024-03-01T12:00:00+00:00[UTC]"),
    ("2023-01-31T12:00:00+00:00[UTC]", "2023-02-28T11:00:00+00:00[UTC]"),
    ("2024-02-29T00:00:00+00:00[UTC]", "2025-02-28T00:00:00+00:00[UTC]"),
    ("2024-02-29T00:00:00+00:00[UTC]", "2028-02-29T00:00:00+00:00[UTC]"),
    ("2024-03-31T09:00:00+00:00[UTC]", "2024-04-30T08:00:00+00:00[UTC]"),
    // New York's 2024 gap (10 March 02:00 to 03:00).
    ("2024-03-09T02:30:00-05:00[America/New_York]", "2024-03-10T03:45:00-04:00[America/New_York]"),
    ("2024-03-09T02:30:00-05:00[America/New_York]", "2024-03-10T03:15:00-04:00[America/New_York]"),
    ("2024-03-09T09:30:00-05:00[America/New_York]", "2024-03-16T09:30:00-04:00[America/New_York]"),
    ("2024-03-10T01:59:59-05:00[America/New_York]", "2024-03-10T03:00:00-04:00[America/New_York]"),
    ("2024-02-10T02:30:00-05:00[America/New_York]", "2024-03-10T04:00:00-04:00[America/New_York]"),
    // New York's 2024 fold (3 November 01:00 to 02:00 twice).
    ("2024-11-02T01:30:00-04:00[America/New_York]", "2024-11-03T01:30:00-04:00[America/New_York]"),
    ("2024-11-02T01:30:00-04:00[America/New_York]", "2024-11-03T01:30:00-05:00[America/New_York]"),
    ("2024-11-02T12:00:00-04:00[America/New_York]", "2024-11-03T12:00:00-05:00[America/New_York]"),
    ("2024-10-03T01:30:00-04:00[America/New_York]", "2024-11-03T01:45:00-05:00[America/New_York]"),
    // Lord Howe's 30-minute shift and Apia's skipped 30 December 2011.
    ("2024-04-06T01:45:00+11:00[Australia/Lord_Howe]", "2024-04-07T01:45:00+10:30[Australia/Lord_Howe]"),
    ("2011-12-29T12:00:00-10:00[Pacific/Apia]", "2011-12-31T12:00:00+14:00[Pacific/Apia]"),
    ("2011-12-28T12:00:00-10:00[Pacific/Apia]", "2012-01-28T11:00:00+14:00[Pacific/Apia]"),
    // Before 1970, nanoseconds, and a fixed offset.
    ("1965-07-01T00:00:00.000000001+00:00[UTC]", "1970-01-01T00:00:00+00:00[UTC]"),
    ("2024-06-01T10:00:00+05:30[+05:30]", "2026-03-15T09:15:00+05:30[+05:30]"),
];

const UNITS: &[(Unit, &str)] = &[
    (Unit::Year, "Year"),
    (Unit::Month, "Month"),
    (Unit::Week, "Week"),
    (Unit::Day, "Day"),
    (Unit::Hour, "Hour"),
    (Unit::Minute, "Minute"),
    (Unit::Second, "Second"),
    (Unit::Nanosecond, "Nanosecond"),
];

fn fields(span: &Span) -> String {
    let nanos = span.get_milliseconds() as i64 * 1_000_000
        + span.get_microseconds() * 1_000
        + span.get_nanoseconds();
    format!(
        "({}, {}, {}, {}, {}, {}, {}, {})",
        span.get_years(),
        span.get_months(),
        span.get_weeks(),
        span.get_days(),
        span.get_hours(),
        span.get_minutes(),
        span.get_seconds(),
        nanos
    )
}

fn main() {
    std::panic::set_hook(Box::new(|_| {}));
    println!("# Generated by scripts/jiff-until with jiff 0.2.31; do not edit.");
    println!("# Each line checks Zoned.until or Zoned.since against jiff, with");
    println!("# Disambiguation.Compatible, the resolution jiff always uses.");
    println!("import std.test");
    println!("import tz");
    println!();
    println!("type Problem = std.test.TestError | AllocError | tz.TzError");
    println!();
    println!("def fields(span: &tz.Span) -> (i64, i64, i64, i64, i64, i64, i64, i64):");
    println!("    (span.years(), span.months(), span.weeks(), span.days(), span.hours(), span.minutes(), span.seconds(), span.nanoseconds())");
    println!();
    println!("def until(start: &str, end: &str, largest: tz.Unit, expected: (i64, i64, i64, i64, i64, i64, i64, i64)) -> Result[(), Problem]:");
    println!("    first = tz.parse_zoned(start)?");
    println!("    second = tz.parse_zoned(end)?");
    println!("    std.test.equal(&fields(&first.until(&second, largest, tz.Disambiguation.Compatible)?), &expected)");
    println!();
    println!("def since(start: &str, end: &str, largest: tz.Unit, expected: (i64, i64, i64, i64, i64, i64, i64, i64)) -> Result[(), Problem]:");
    println!("    first = tz.parse_zoned(start)?");
    println!("    second = tz.parse_zoned(end)?");
    println!("    std.test.equal(&fields(&first.since(&second, largest, tz.Disambiguation.Compatible)?), &expected)");
    for (index, (a, b)) in PAIRS.iter().enumerate() {
        let first: Zoned = a.parse().unwrap();
        let second: Zoned = b.parse().unwrap();
        println!();
        println!("def test_case_{index:02}() -> Result[(), Problem]:");
        for (x, y, xs, ys) in [(&first, &second, a, b), (&second, &first, b, a)] {
            for (unit, name) in UNITS {
                let until = std::panic::catch_unwind(|| x.until((*unit, y)));
                if let Ok(Ok(span)) = until {
                    println!("    until(&\"{xs}\", &\"{ys}\", tz.Unit.{name}, {})?", fields(&span));
                }
            }
        }
        for (unit, name) in &UNITS[..4] {
            let since = std::panic::catch_unwind(|| first.since((*unit, &second)));
            if let Ok(Ok(span)) = since {
                println!("    since(&\"{a}\", &\"{b}\", tz.Unit.{name}, {})?", fields(&span));
            }
        }
        println!("    Ok(())");
    }
}
